#!/usr/bin/env bash
# acceptance.sh run|report - the spec section 8 acceptance run, mechanical.
#   run     make distclean, then make check, make all, make pnr-check and the self-tests that sit outside check,
#           logging each into build/reports/ with its exit status and wall time (build/reports/exit_status.txt),
#           then 'report'. Takes several minutes.
#           After 'run': scripts/snapshot.sh final ; python3 scripts/readme_results.py final ; scripts/acceptance.sh report
#   report  rewrite docs/acceptance.txt from those logs: an item is PASS only if its proving line is in the log.
set -u
cd "$(dirname "$0")/.."
R=build/reports
mode=${1:-report}

if [ "$mode" = run ]; then
  make distclean > /dev/null
  mkdir -p "$R"
  : > "$R/exit_status.txt"
  step() { # <name> <log> <command...>
    local name=$1 log=$2; shift 2
    local t0=$SECONDS
    "$@" > "$log" 2>&1
    local rc=$?
    echo "$name exit=$rc wall_seconds=$((SECONDS - t0))" | tee -a "$R/exit_status.txt"
  }
  step check       "$R/check.log"     make check
  step all         "$R/all.log"       make all
  step pnr-check   "$R/pnr-check.log" make pnr-check
  step selftests   "$R/selftests.log" make synth-selftest sta-selftest summary-selftest pnr-selftest synth-selftest-deep
fi

status() { # <description of the proving condition>  (reads $? of the preceding test)
  if [ "$1" = 0 ]; then echo PASS; else echo "FAIL"; fi
}
have() { grep -q -- "$2" "$1" 2>/dev/null; }
exit_of() { sed -n "s/^$1 exit=\([0-9]*\) .*/\1/p" "$R/exit_status.txt" 2>/dev/null | head -n 1; }
wall_of() { sed -n "s/^$1 exit=[0-9]* wall_seconds=\([0-9]*\)/\1/p" "$R/exit_status.txt" 2>/dev/null | head -n 1; }

out=docs/acceptance.txt
{
echo "# Acceptance - spec section 8 (docs/superpowers/specs/2026-10-19-alu-fifo-design.md)"
echo "# Generated by scripts/acceptance.sh from the logs in build/reports/ of the last 'scripts/acceptance.sh run'."
echo "# An item is PASS only if its proving line is in the log; otherwise FAIL (or NOT YET RUN if there is no log)."
echo
if [ ! -s "$R/exit_status.txt" ]; then echo "NOT YET RUN: no $R/exit_status.txt (run: scripts/acceptance.sh run)"; exit 0; fi

item() { # <number> <title> <PASS|FAIL> <evidence lines...>
  local n=$1 title=$2 st=$3; shift 3
  echo "$n. $title"
  echo "   status : $st"
  for l in "$@"; do echo "   proof  : $l"; done
  echo
}
tf() { "$@" && echo PASS || echo FAIL; }

# 1 lint
item 1 "make lint reports zero warnings on rtl/ ($R/check.log)" \
  "$(tf have $R/check.log '^\[LINT\] clean')" "$(grep -m1 '^\[LINT\] clean' $R/check.log)"
# 2 sim
item 2 "make sim exits 0 with TB PASS; the same seed reproduces the run" \
  "$(tf bash -c "grep -q '^TB PASS seed=1' $R/check.log && grep -q 'SEED=1 reproduces byte-identically' $R/check.log")" \
  "$(grep -m1 '^TB PASS seed=1' $R/check.log)" "$(grep -m1 'SEED=1 reproduces' $R/check.log)"
# 3 cov
cov_ok=FAIL
if have $R/check.log 'cov_check: ok' && have $R/coverage_summary.txt ', 0 zero' && have $R/coverage_summary.txt ', 0 uncovered'; then cov_ok=PASS; fi
item 3 "make cov: every named bin hit, rtl/ line coverage 100% apart from named exclusions" "$cov_ok" \
  "$(grep -m1 'cov_check:' $R/check.log)" "$(grep -m1 'named cover bins' $R/coverage_summary.txt)" \
  "$(grep -m1 'line blocks' $R/coverage_summary.txt)" "exclusions file: verif/cov_exclusions.txt ($(grep -vc '^#\|^$' verif/cov_exclusions.txt) entries)"
# 4 mutants
mut_ok=FAIL
mline=$(grep -m1 '^mutants: [0-9]*, killed' $R/mutants.txt 2>/dev/null)
if [ -n "$mline" ] && ! have $R/mutants.txt '^PROBLEMS' && have $R/mutants.txt '^assertions with no mutant bound to them  : none' \
   && have $R/mutants.txt '^assertions that fired in no mutant run   : none'; then
  n=$(echo "$mline" | sed -n 's/^mutants: \([0-9]*\), killed \([0-9]*\), intended check fired in \([0-9]*\)/\1/p')
  k=$(echo "$mline" | sed -n 's/^mutants: \([0-9]*\), killed \([0-9]*\), intended check fired in \([0-9]*\)/\2/p')
  i=$(echo "$mline" | sed -n 's/^mutants: \([0-9]*\), killed \([0-9]*\), intended check fired in \([0-9]*\)/\3/p')
  [ "$n" = "$k" ] && [ "$n" = "$i" ] && [ "$n" -gt 0 ] && mut_ok=PASS
fi
item 4 "make mutants: every mutant killed, its intended check fired, neutralised-check run shown, every assertion bound to a mutant and fired" "$mut_ok" \
  "$mline" "$(grep -m1 '^only guard' $R/mutants.txt)" "$(grep -m1 '^assertions defined' $R/mutants.txt)" \
  "$(grep -m1 '^assertions with no mutant' $R/mutants.txt)" "$(grep -m1 '^assertions that fired in no' $R/mutants.txt)" "detail: $R/mutants.txt"
# 5 synth
s5=FAIL
if have $R/all.log '\[SYNTH\] Netlist ready' && have build/netlist_check.log '^PASS all-mapped' && have build/synth.log '^PASS check-rtl' \
   && [ "$(grep -c 'lpflow' build/synth.v)" = 0 ] && ! have $R/selftests.log '^FAIL'; then s5=PASS; fi
item 5 "make synth: checks clean, netlist only Sky130 HD library cells, no lpflow cells" "$s5" \
  "$(grep -m1 '\[SYNTH\] Netlist ready' $R/all.log)" "build/synth.log and build/netlist_check.log: CHECK/PASS pairs for check-rtl, no-tribuf, no-latch, check-assert, all-mapped, no-lpflow" \
  "lpflow cells in build/synth.v: $(grep -c lpflow build/synth.v)" "$(grep -m1 'Number of cells' $R/stat.txt)" "$(grep -m1 'Chip area' $R/stat.txt)"
# 6 sta
item 6 "make sta: the SDC's clock period equals CLK_PERIOD_NS; timing and power reports written" \
  "$(tf have $R/all.log '^check_sdc: ok')" "$(grep -m1 '^check_sdc:' $R/all.log)" "$R/sdc_readback.sdc $R/timing.txt $R/power_report.txt"
# 7 pnr
p7=FAIL
if have $R/pnr-check.log '^ok   drc_violations=' && ! have $R/pnr-check.log '^FAIL' && [ "$(exit_of pnr-check)" = 0 ]; then p7=PASS; fi
item 7 "make pnr completes and writes the spec 6.5 reports incl. DRC count and antenna result (a non-zero count or failing slack is reported, not hidden)" "$p7" \
  "$(grep -m1 'drc_violations=' pnr_results/drc_count.txt)" "$(grep -m1 'antenna_violations=' pnr_results/antenna.rpt)" \
  "routed worst setup / hold / TNS: $(grep -E '^worst slack max' pnr_results/timing_final.rpt) / $(grep -E '^worst slack min' pnr_results/timing_final.rpt) / $(grep -E '^tns max' pnr_results/timing_final.rpt)" \
  "pnr-check: $(grep -c '^ok' $R/pnr-check.log) checks ok, $(grep -c '^FAIL' $R/pnr-check.log) failed" \
  "routed slew/cap/fanout violations (reported, not gated): $(grep -m1 'slew/cap/fanout, routed' $R/../../docs/results/final/summary.txt 2>/dev/null | sed 's/^ *//')"
# 8 clean checkout
c=$(exit_of check); a=$(exit_of all)
readme_msg=$(python3 -I scripts/readme_results.py final --check 2>&1); readme_rc=$?
a8=FAIL; [ "$c" = 0 ] && [ "$a" = 0 ] && [ "$readme_rc" = 0 ] && a8=PASS
item 8 "make check and make all both run from a clean tree (scripts/acceptance.sh run starts with make distclean); the README results block is the snapshot, verbatim" "$a8" \
  "make check exit=$c wall_seconds=$(wall_of check)" "make all exit=$a wall_seconds=$(wall_of all)" \
  "self-tests outside check (synth, sta, summary, synth deep): exit=$(exit_of selftests) wall_seconds=$(wall_of selftests), $(grep -c '^ok' $R/selftests.log) ok / $(grep -c '^FAIL' $R/selftests.log) FAIL" \
  "$readme_msg"
} > "$out"
echo "acceptance: wrote $out ($(grep -c 'status : PASS' "$out") PASS, $(grep -c 'status : FAIL' "$out") FAIL)"
