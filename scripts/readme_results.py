#!/usr/bin/env python3
"""readme_results.py LABEL [--readme README.md] [--check]

Replaces the block between <!-- BEGIN RESULTS --> and <!-- END RESULTS --> in the README with the contents of
the report snapshot docs/results/LABEL/, quoted verbatim. No figure is typed by hand: the README can only show
what a tool wrote into a checked-in report. A report that is not in the snapshot is listed as NOT YET MEASURED.
With --check nothing is written: exit 0 if the README block is exactly what the snapshot produces, else exit 1.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN, END = "<!-- BEGIN RESULTS", "<!-- END RESULTS -->"


def read(path):
    try:
        with open(path) as fh:
            return fh.read().rstrip("\n")
    except OSError:
        return None


def section(title, body, source, command):
    if body is None:
        return f"**{title}**: NOT YET MEASURED (`{command}`)\n"
    return f"**{title}** - from `{source}`\n\n```text\n{body}\n```\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("label")
    ap.add_argument("--readme", default=os.path.join(ROOT, "README.md"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    d = os.path.join(ROOT, "docs", "results", args.label)
    if not os.path.isdir(d):
        sys.exit(f"readme_results: {d} does not exist (run scripts/snapshot.sh {args.label})")
    rel = f"docs/results/{args.label}"

    mut = read(f"{d}/mutants.txt")
    mut_tail = None
    if mut:
        mut_tail = "\n".join(l for l in mut.splitlines() if l.startswith(("mutants:", "only guard", "assertions ", "PROBLEMS")))

    blocks = [
        section("Conditions of the run", read(f"{d}/run.txt"), f"{rel}/run.txt", "scripts/snapshot.sh <label>"),
        section("Key figures (make summary)", read(f"{d}/summary.txt"), f"{rel}/summary.txt", "make summary"),
        section("Coverage", read(f"{d}/coverage_summary.txt"), f"{rel}/coverage_summary.txt", "make cov"),
        section("Mutation run", mut_tail, f"{rel}/mutants.txt", "make mutants"),
    ]
    block = f"{BEGIN} (generated by scripts/readme_results.py from {rel}/; do not edit by hand) -->\n\n" + \
            "\n".join(blocks) + f"\n{END}"

    text = read(args.readme)
    if text is None:
        sys.exit(f"readme_results: cannot read {args.readme}")
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        sys.exit(f"readme_results: {args.readme} has no '{BEGIN} ... {END}' block")
    new_text = pat.sub(lambda _: block, text)
    if args.check:
        if new_text == text:
            print(f"readme_results: ok, the README results block is exactly {rel}/ quoted verbatim")
            return
        print(f"readme_results: FAIL, the README results block differs from {rel}/ (run: python3 scripts/readme_results.py {args.label})")
        sys.exit(1)
    with open(args.readme, "w") as fh:
        fh.write(new_text + "\n")
    print(f"readme_results: README results block now quotes {rel}/")


if __name__ == "__main__":
    main()
